"""BountyLoop — Common shared Pydantic schemas.

Provides RFC-7807 Problem Details and generic pagination schemas.
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class ProblemDetails(BaseModel):
    """RFC-7807 Problem Details schema for HTTP APIs."""

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        ...,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="Validation error details for 422 Unprocessable Entity responses.",
    )


class PaginationParams(BaseModel):
    """Standard pagination query parameters."""

    page: int = Field(default=1, ge=1, description="Page number (1-indexed)")
    page_size: int = Field(default=20, ge=1, le=100, description="Items per page")

    @property
    def offset(self) -> int:
        """Compute SQL offset from page and page_size."""
        return (self.page - 1) * self.page_size


class PaginatedResponse[T](BaseModel):
    """Generic paginated response envelope."""

    items: list[T] = Field(description="Page items")
    total: int = Field(description="Total count across all pages")
    page: int = Field(description="Current page number")
    page_size: int = Field(description="Items per page")
    total_pages: int = Field(description="Total number of pages")
